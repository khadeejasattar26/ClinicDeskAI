import request from 'supertest';
import { createClient } from '@supabase/supabase-js';
import { createApp } from '../src/app';
import { createServices } from '../src/services';
import { loadConfig } from '../src/config';
import { MemoryRepository, SupabaseRepository } from '../src/repository';
import { CLINIC_ID } from '../src/demo-data';
const config = loadConfig({ NODE_ENV: 'test', MOCK_LLM: 'true', DEMO_MODE: 'true' });
const setup = () => { const services = createServices(config); return { app: createApp(config, services), repo: services.repo as MemoryRepository }; };
const endpoints = ['/appointments','/leads','/conversations','/conversations/11111111-1111-4111-8111-111111111111','/usage'];
test.each(endpoints)('admin %s requires a verified staff token', async endpoint => {
  const { app } = setup();
  expect((await request(app).get('/api/admin'+endpoint)).status).toBe(401);
  expect((await request(app).get('/api/admin'+endpoint).set('Authorization','Bearer invalid')).status).toBe(401);
});
test('admin lists and transcripts are scoped, paginated and never cached', async () => {
  const { app, repo } = setup();
  const own = await repo.conversation(CLINIC_ID);
  const other = await repo.conversation('other-clinic');
  await repo.addMessage(own.id,'user','My visit');
  await repo.addMessage(other.id,'user','Private other clinic');
  await repo.createLead(CLINIC_ID,{name:'Demo',contact:'demo@example.com',message:'Call me'});
  await repo.createLead('other-clinic',{name:'Other',contact:'private@example.com',message:'Secret'});
  const get = (path: string) => request(app).get('/api/admin'+path).set('Authorization','Bearer local-demo-staff');
  const leads = await get('/leads?clinicId=other-clinic&limit=1');
  expect(leads.status).toBe(200);
  expect(leads.headers['cache-control']).toBe('no-store');
  expect(leads.body.items).toHaveLength(1);
  expect(leads.body.items[0].name).toBe('Demo');
  expect((await get('/conversations')).body.items).toHaveLength(1);
  expect((await get('/conversations/'+own.id)).body.messages[0].content).toBe('My visit');
  expect((await get('/conversations/'+other.id)).status).toBe(404);
  expect((await get('/conversations/not-uuid')).status).toBe(400);
  expect((await get('/appointments?limit=101')).status).toBe(400);
  expect((await get('/leads?offset=-1')).status).toBe(400);
  expect((await get('/appointments')).body.items).toEqual([]);
});
test('usage totals exclude other clinics and mock cost is zero', async () => {
  const { app, repo } = setup();
  const own = await repo.conversation(CLINIC_ID), other = await repo.conversation('other');
  expect((await repo.usage(CLINIC_ID)).total_calls).toBe(0);
  const usage = { model:'mock',prompt_tokens:100,completion_tokens:20,latency_ms:10,estimated_cost_usd:0 };
  await repo.logUsage({ ...usage,conversation_id:own.id });
  await repo.logUsage({ ...usage,conversation_id:other.id });
  const res = await request(app).get('/api/admin/usage').set('Authorization','Bearer local-demo-staff');
  expect(res.body).toMatchObject({ total_tokens:120,total_calls:1,total_cost_usd:0,average_latency_ms:10,mock:true });
  expect(res.body.daily).toHaveLength(1);
});
test('Supabase staff auth validates the JWT and denies users without a membership', async () => {
  let data: unknown = { user: { id:'staff-id' } };
  const fetcher = jest.fn(async (url: RequestInfo | URL, _init?: RequestInit) => new Response(JSON.stringify(String(url).includes('/auth/') ? data : { clinic_id:CLINIC_ID }),{headers:{'content-type':'application/json'}}));
  const repo = new SupabaseRepository(createClient('https://clinic.example.com','fake',{global:{fetch:fetcher},auth:{persistSession:false}}));
  expect(await repo.staffClinic('token')).toBe(CLINIC_ID);
  expect(fetcher.mock.calls.some(c => String(c[0]).includes('/auth/v1/user'))).toBe(true);
  data = { user:null };
  await expect(repo.staffClinic('bad')).rejects.toMatchObject({status:401});
  const db = createClient('https://clinic.example.com','fake',{global:{fetch:async (url) => new Response(JSON.stringify(String(url).includes('/auth/') ? {id:'staff-id'} : null),{headers:{'content-type':'application/json'}})},auth:{persistSession:false}});
  await expect(new SupabaseRepository(db).staffClinic('token')).rejects.toMatchObject({status:403});
});
test('Supabase admin queries scope rows before pagination and verify transcript ownership', async () => {
  let data: unknown = [{id:'appointment',slots:{starts_at:'2026-11-02T04:00:00Z'}}];
  const fetcher = jest.fn(async (_url: RequestInfo | URL, _init?: RequestInit) => new Response(JSON.stringify(data),{headers:{'content-type':'application/json'}}));
  const repo = new SupabaseRepository(createClient('https://clinic.example.com','fake',{global:{fetch:fetcher},auth:{persistSession:false}}));
  expect((await repo.list(CLINIC_ID,'appointments',0,10))[0].starts_at).toBe('2026-11-02T04:00:00Z');
  expect(String(fetcher.mock.calls[0][0])).toContain('clinic_id=eq.'+CLINIC_ID);
  await repo.list(CLINIC_ID,'leads',0,10);
  data = {id:'conversation'};
  await repo.transcript(CLINIC_ID,'conversation',0,50);
  data = { total_calls:0 };
  expect(await repo.usage(CLINIC_ID)).toEqual({total_calls:0});
  expect(JSON.parse(String(fetcher.mock.calls.at(-1)![1]?.body))).toEqual({p_clinic_id:CLINIC_ID});
});
